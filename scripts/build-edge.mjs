// Bundles the split-teams edge function's pure part (src/server/splitTeams.ts + the app's balancing
// code it imports) into supabase/functions/split-teams/core.js, so the server splits with exactly
// the app's code and the function deploys as plain files (index.ts + core.js). The output is
// committed; src/server/splitTeams.test.ts fails when it is out of date. Run: node scripts/build-edge.mjs
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const EDGE_OUT = `${root}supabase/functions/split-teams/core.js`;
export const EDGE_URL = new URL('../supabase/functions/split-teams/core.js', import.meta.url).href;

/** The committed bundle ('' when missing). */
export function readEdge() {
  try {
    return readFileSync(EDGE_OUT, 'utf8');
  } catch {
    return '';
  }
}
const BANNER = '// GENERATED by scripts/build-edge.mjs from src/server/splitTeams.ts — do not edit by hand.\n// deno-lint-ignore-file\n';

/** The bundle as text (nothing written). */
export async function bundleEdge() {
  const r = await build({
    entryPoints: [`${root}src/server/splitTeams.ts`],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    legalComments: 'none',
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleEdge();
  const old = readEdge();
  if (old === text) console.log('core.js up to date');
  else {
    writeFileSync(EDGE_OUT, text);
    console.log(`wrote ${EDGE_OUT} (${text.length} bytes)`);
  }
}
